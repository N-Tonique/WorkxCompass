import type { GraphCard } from "@/types/knowledge";

type LocalSourceType = "pdf" | "teams" | "expert_note" | "procedure" | "email";

type CardInput = {
  id: string;
  title: string;
  summary: string;
  sourceType: LocalSourceType;
  country?: string[];
  domain?: string[];
  topics?: string[];
  client?: string[];
  validFrom?: string;
  owner?: string;
  sourceLabel: string;
  sourceUrl?: string;
  sourceExcerpt: string;
  conflictGroup?: string;
};

const createCard = ({
  sourceLabel,
  sourceUrl,
  sourceExcerpt,
  conflictGroup,
  country,
  domain,
  topics,
  client,
  validFrom,
  ...card
}: CardInput): GraphCard => {
  const format =
    card.sourceType === "teams"
      ? "teams"
      : card.sourceType === "email"
        ? "email_msg"
        : "pdf";
  const domaine = domain?.[0] ?? "General";
  const sousDomaine = topics?.[0] ?? "General knowledge";

  return {
    id: card.id,
    title: card.title,
    summary: `${card.summary} Source evidence: ${sourceExcerpt}`,
    source: {
      format,
      uri: sourceUrl ?? sourceLabel,
      markdownPath: `/knowledge/${card.id}.md`,
      revisionId: `rev-${card.id}-2026-09-30`,
    },
    classification: {
      domaine,
      sousDomaine,
      pays: country?.[0],
      client: client?.[0],
      validFrom,
    },
    knowledgeType: `${domaine}/${sousDomaine}`,
    decisionStatus: conflictGroup ? "needs_expert" : "approved",
  };
};

